// setBaseURL overrides the package-level baseURL for the duration of a test.
func setBaseURL(t *testing.T, url string) {
	t.Helper()
	old := baseURL
	baseURL = url
	t.Cleanup(func() { baseURL = old })
}

// setVersion overrides the build version for the duration of a test.
func setVersion(t *testing.T, v string) {
	t.Helper()
	old := version.Version
	version.Version = v
	t.Cleanup(func() { version.Version = old })
}

// writeTarGz builds an in-memory tar.gz archive with the given name → content entries.
func writeTarGz(t *testing.T, entries map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	gzw := gzip.NewWriter(&buf)
	tw := tar.NewWriter(gzw)
	for name, content := range entries {
		hdr := &tar.Header{
			Name:     name,
			Mode:     0o755,
			Size:     int64(len(content)),
			Typeflag: tar.TypeReg,
		}
		if err := tw.WriteHeader(hdr); err != nil {
			t.Fatalf("write tar header %s: %v", name, err)
		}
		if _, err := tw.Write([]byte(content)); err != nil {
			t.Fatalf("write tar entry %s: %v", name, err)
		}
	}
	if err := tw.Close(); err != nil {
		t.Fatalf("close tar: %v", err)
	}
	if err := gzw.Close(); err != nil {
		t.Fatalf("close gzip: %v", err)
	}
	return buf.Bytes()
}

// writeZipBytes builds an in-memory zip archive with the given name → content entries.
func writeZipBytes(t *testing.T, entries map[string]string) []byte {
	t.Helper()
	var buf bytes.Buffer
	w := zip.NewWriter(&buf)
	for name, content := range entries {
		fw, err := w.Create(name)
		if err != nil {
			t.Fatalf("create zip entry %s: %v", name, err)
		}
		if _, err := fw.Write([]byte(content)); err != nil {
			t.Fatalf("write zip entry %s: %v", name, err)
		}
	}
	if err := w.Close(); err != nil {
		t.Fatalf("close zip: %v", err)
	}
	return buf.Bytes()
}

// writeTestZip creates a zip file at path with the given name → content entries.
func writeTestZip(t *testing.T, path string, entries map[string]string) {
	t.Helper()
	if err := os.WriteFile(path, writeZipBytes(t, entries), 0o644); err != nil {
		t.Fatalf("write zip: %v", err)
	}
}

// writePlatformArchive builds the archive type the updater expects for the
// current platform: zip on Windows, tar.gz elsewhere.
func writePlatformArchive(t *testing.T, entries map[string]string) []byte {
	t.Helper()
	if runtime.GOOS == "windows" {
		return writeZipBytes(t, entries)
	}
	return writeTarGz(t, entries)
}

func TestParseChecksums(t *testing.T) {
	validSum := strings.Repeat("ab", 32) // 64 hex chars

	tests := []struct {
		name  string
		input string
		want  map[string]string
	}{
		{
			name:  "single entry double space",
			input: validSum + "  bino-cli_Linux_x86_64.tar.gz\n",
			want:  map[string]string{"bino-cli_Linux_x86_64.tar.gz": validSum},
		},
		{
			name:  "single entry single space",
			input: validSum + " bino-cli_Windows_x86_64.zip\n",
			want:  map[string]string{"bino-cli_Windows_x86_64.zip": validSum},
		},
		{
			name: "skips comments and blank lines",
			input: "# generated by goreleaser\n\n" +
				validSum + "  asset.tar.gz\n",
			want: map[string]string{"asset.tar.gz": validSum},
		},
		{
			name:  "skips short checksum",
			input: "deadbeef  asset.tar.gz\n",
			want:  map[string]string{},
		},
		{
			name:  "skips malformed lines",
			input: "one\n" + validSum + " too many fields\n",
			want:  map[string]string{},
		},
		{
			name:  "empty input",
			input: "",
			want:  map[string]string{},
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			got, err := parseChecksums(strings.NewReader(tt.input))
			if err != nil {
				t.Fatalf("parseChecksums() error = %v", err)
			}
			if len(got) != len(tt.want) {
				t.Fatalf("parseChecksums() = %v, want %v", got, tt.want)
			}
			for name, sum := range tt.want {
				if got[name] != sum {
					t.Errorf("checksum for %s = %q, want %q", name, got[name], sum)
				}
			}
		})
	}
}

func TestExtractBinaryFromTarGz(t *testing.T) {
	tests := []struct {
		name    string
		entries map[string]string
		want    string
		wantErr string
	}{
		{
			name:    "extracts bino",
			entries: map[string]string{"README.md": "docs", "bino": "binary-content"},
			want:    "binary-content",
		},
		{
			name:    "extracts bino.exe",
			entries: map[string]string{"bino.exe": "exe-content"},
			want:    "exe-content",
		},
		{
			name:    "binary missing",
			entries: map[string]string{"README.md": "docs"},
			wantErr: "bino binary not found",
		},
		{
			name: "ignores path-escaping entry names",
			entries: map[string]string{
				"../bino":     "evil",
				"sub/bino":    "nested",
				"bino.backup": "other",
			},
			wantErr: "bino binary not found",
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			archive := writeTarGz(t, tt.entries)
			var out bytes.Buffer

			err := extractBinaryFromTarGz(bytes.NewReader(archive), &out)
			if tt.wantErr != "" {
				if err == nil {
					t.Fatal("extractBinaryFromTarGz() should error")
				}
				if !strings.Contains(err.Error(), tt.wantErr) {
					t.Errorf("error = %v, want %s", err, tt.wantErr)
				}
				return
			}
			if err != nil {
				t.Fatalf("extractBinaryFromTarGz() error = %v", err)
			}
			if out.String() != tt.want {
				t.Errorf("extracted content = %q, want %q", out.String(), tt.want)
			}
		})
	}

	t.Run("invalid gzip errors", func(t *testing.T) {
		err := extractBinaryFromTarGz(strings.NewReader("not gzip"), &bytes.Buffer{})
		if err == nil {
			t.Fatal("extractBinaryFromTarGz() should error on invalid gzip")
		}
		if !strings.Contains(err.Error(), "gzip") {
			t.Errorf("error = %v, want gzip", err)
		}
	})
}


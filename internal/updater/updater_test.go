func TestCheckForUpdate(t *testing.T) {
	t.Run("skips check within 24h interval", func(t *testing.T) {
		t.Setenv("HOME", t.TempDir())
		if err := SaveState(&State{LastUpdateCheck: time.Now()}); err != nil {
			t.Fatalf("SaveState() error = %v", err)
		}

		hits := 0
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			hits++
		}))
		defer srv.Close()
		setBaseURL(t, srv.URL)

		result, err := CheckForUpdate(context.Background())
		if err != nil {
			t.Fatalf("CheckForUpdate() error = %v", err)
		}
		if result != nil {
			t.Errorf("CheckForUpdate() = %+v, want nil", result)
		}
		if hits != 0 {
			t.Errorf("server was hit %d times, want 0", hits)
		}
	})

	t.Run("reports newer version", func(t *testing.T) {
		t.Setenv("HOME", t.TempDir())
		setVersion(t, "1.0.0")

		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			w.Header().Set("Location", "/download/v2.0.0/"+getAssetName())
			w.WriteHeader(http.StatusFound)
		}))
		defer srv.Close()
		setBaseURL(t, srv.URL)

		result, err := CheckForUpdate(context.Background())
		if err != nil {
			t.Fatalf("CheckForUpdate() error = %v", err)
		}
		if result == nil {
			t.Fatal("CheckForUpdate() = nil, want update result")
		}
		if result.LatestVersion != "v2.0.0" {
			t.Errorf("LatestVersion = %q, want v2.0.0", result.LatestVersion)
		}
		if result.CurrentVersion != "1.0.0" {
			t.Errorf("CurrentVersion = %q, want 1.0.0", result.CurrentVersion)
		}

		// The check time must be persisted for the 24h interval.
		state, err := LoadState()
		if err != nil {
			t.Fatalf("LoadState() error = %v", err)
		}
		if state.LastUpdateCheck.IsZero() {
			t.Error("LastUpdateCheck was not persisted")
		}
	})

	t.Run("returns nil when up to date", func(t *testing.T) {
		t.Setenv("HOME", t.TempDir())
		setVersion(t, "2.0.0")

		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			w.Header().Set("Location", "/download/v2.0.0/"+getAssetName())
			w.WriteHeader(http.StatusFound)
		}))
		defer srv.Close()
		setBaseURL(t, srv.URL)

		result, err := CheckForUpdate(context.Background())
		if err != nil {
			t.Fatalf("CheckForUpdate() error = %v", err)
		}
		if result != nil {
			t.Errorf("CheckForUpdate() = %+v, want nil", result)
		}
	})
}

func TestUpdate(t *testing.T) {
	t.Run("already up to date returns nil without download", func(t *testing.T) {
		setVersion(t, "2.0.0")

		downloads := 0
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			if r.Method == http.MethodGet {
				downloads++
			}
			w.Header().Set("Location", "/download/v1.0.0/"+getAssetName())
			w.WriteHeader(http.StatusFound)
		}))
		defer srv.Close()
		setBaseURL(t, srv.URL)

		result, err := Update(context.Background(), nil)
		if err != nil {
			t.Fatalf("Update() error = %v", err)
		}
		if result != nil {
			t.Errorf("Update() = %+v, want nil", result)
		}
		if downloads != 0 {
			t.Errorf("downloads = %d, want 0", downloads)
		}
	})

	t.Run("checksum mismatch aborts update", func(t *testing.T) {
		setVersion(t, "1.0.0")

		assetName := getAssetName()
		archive := writePlatformArchive(t, map[string]string{"bino": "new-binary"})
		wrongSum := strings.Repeat("00", 32)

		var serverURL string
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			switch {
			case strings.HasSuffix(r.URL.Path, "/latest/download/"+assetName):
				w.Header().Set("Location", serverURL+"/download/v2.0.0/"+assetName)
				w.WriteHeader(http.StatusFound)
			case strings.HasSuffix(r.URL.Path, "/checksums.txt"):
				fmt.Fprintf(w, "%s  %s\n", wrongSum, assetName)
			case strings.HasSuffix(r.URL.Path, "/download/v2.0.0/"+assetName):
				_, _ = w.Write(archive)
			default:
				http.NotFound(w, r)
			}
		}))
		serverURL = srv.URL
		defer srv.Close()
		setBaseURL(t, srv.URL)

		var progress []string
		_, err := Update(context.Background(), func(msg string) { progress = append(progress, msg) })
		if err == nil {
			t.Fatal("Update() should fail on checksum mismatch")
		}
		if !strings.Contains(err.Error(), "checksum mismatch") {
			t.Errorf("error = %v, want checksum mismatch", err)
		}
		if len(progress) == 0 {
			t.Error("progress callback was never invoked")
		}
	})

	t.Run("matching checksum passes verification", func(t *testing.T) {
		setVersion(t, "1.0.0")

		assetName := getAssetName()
		// Archive deliberately lacks the binary so the update aborts at the
		// extraction step — after checksum verification but before the test
		// binary would be replaced.
		archive := writePlatformArchive(t, map[string]string{"README.md": "no binary"})
		sum := sha256.Sum256(archive)
		goodSum := hex.EncodeToString(sum[:])

		var serverURL string
		srv := httptest.NewServer(http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
			switch {
			case strings.HasSuffix(r.URL.Path, "/latest/download/"+assetName):
				w.Header().Set("Location", serverURL+"/download/v2.0.0/"+assetName)
				w.WriteHeader(http.StatusFound)
			case strings.HasSuffix(r.URL.Path, "/checksums.txt"):
				fmt.Fprintf(w, "%s  %s\n", goodSum, assetName)
			case strings.HasSuffix(r.URL.Path, "/download/v2.0.0/"+assetName):
				_, _ = w.Write(archive)
			default:
				http.NotFound(w, r)
			}
		}))
		serverURL = srv.URL
		defer srv.Close()
		setBaseURL(t, srv.URL)

		_, err := Update(context.Background(), nil)
		if err == nil {
			t.Fatal("Update() should fail at extraction")
		}
		if strings.Contains(err.Error(), "checksum mismatch") {
			t.Errorf("Update() failed checksum verification: %v", err)
		}
		if !strings.Contains(err.Error(), "bino binary not found") {
			t.Errorf("error = %v, want bino binary not found", err)
		}
	})
}

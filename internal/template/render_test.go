// TestRenderForceOverwrite confirms force lets a re-render overwrite existing
// files while the default path refuses.
func TestRenderForceOverwrite(t *testing.T) {
	root, err := BuiltinRoot("minimal")
	if err != nil {
		t.Fatal(err)
	}
	manifest, err := BuiltinManifest("minimal")
	if err != nil {
		t.Fatal(err)
	}
	dest := t.TempDir()
	if _, err := RenderTree(root, manifest, dest, minimalGoldenData(), false); err != nil {
		t.Fatal(err)
	}
	if _, err := RenderTree(root, manifest, dest, minimalGoldenData(), false); err == nil {
		t.Fatal("expected error re-rendering without force")
	}
	if _, err := RenderTree(root, manifest, dest, minimalGoldenData(), true); err != nil {
		t.Fatalf("force re-render failed: %v", err)
	}
}

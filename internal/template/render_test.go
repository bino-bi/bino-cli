// minimalGoldenData mirrors the values `bino init -y` derives for the default
// answers, with the non-deterministic vars (.ReportID/.Date/.EngineVersion)
// pinned so the output can be compared against committed golden files.
func minimalGoldenData() map[string]any {
	return map[string]any{
		"ReportName":     "rainbow-sample-report",
		"ReportTitle":    "Rainbow Sample Report",
		"Language":       "en",
		"Filename":       "rainbow-sample-report.pdf",
		"LayoutName":     "rainbow-sample-report-page",
		"DataSourceName": "rainbow_sample_report_data",
		"ReportID":       "00000000-0000-0000-0000-000000000000",
		"EngineVersion":  "v1.0.0-alpha.15",
		"Date":           "2026-01-01T00:00:00Z",
		"BinoVersion":    "0.0.0-test",
	}
}

// TestRenderMinimalByteStable is the byte-stability gate: rendering the built-in
// minimal template with fixed inputs must reproduce the historical fmt.Sprintf
// scaffold exactly, file for file.
func TestRenderMinimalByteStable(t *testing.T) {
	root, err := BuiltinRoot("minimal")
	if err != nil {
		t.Fatal(err)
	}
	manifest, err := BuiltinManifest("minimal")
	if err != nil {
		t.Fatal(err)
	}

	dest := t.TempDir()
	created, err := RenderTree(root, manifest, dest, minimalGoldenData(), false)
	if err != nil {
		t.Fatal(err)
	}

	want := []string{".bnignore", ".gitignore", "bino.toml", "data.yaml", "pages.yaml", "report.yaml"}
	if !reflect.DeepEqual(created, want) {
		t.Fatalf("created files = %v, want %v", created, want)
	}

	for _, rel := range created {
		got, err := os.ReadFile(filepath.Join(dest, rel))
		if err != nil {
			t.Fatalf("read rendered %s: %v", rel, err)
		}
		golden, err := os.ReadFile(filepath.Join("testdata", "golden", "minimal", rel))
		if err != nil {
			t.Fatalf("read golden %s: %v", rel, err)
		}
		if !bytes.Equal(got, golden) {
			t.Errorf("%s mismatch:\n--- got ---\n%s\n--- want ---\n%s", rel, got, golden)
		}
	}
}

// TestRenderMinimalNoEngineVersion verifies the conditional engine-version line:
// with no local engine, bino.toml ends right after report-id, matching the old
// best-effort behavior.
func TestRenderMinimalNoEngineVersion(t *testing.T) {
	root, err := BuiltinRoot("minimal")
	if err != nil {
		t.Fatal(err)
	}
	manifest, err := BuiltinManifest("minimal")
	if err != nil {
		t.Fatal(err)
	}

	data := minimalGoldenData()
	data["EngineVersion"] = ""

	dest := t.TempDir()
	if _, err := RenderTree(root, manifest, dest, data, false); err != nil {
		t.Fatal(err)
	}

	got, err := os.ReadFile(filepath.Join(dest, "bino.toml"))
	if err != nil {
		t.Fatal(err)
	}
	want := "# Bino project configuration\n" +
		"# This file marks the root of a bino reporting project.\n" +
		"# Generated by 'bino init' on 2026-01-01T00:00:00Z\n\n" +
		"report-id = \"00000000-0000-0000-0000-000000000000\"\n"
	if string(got) != want {
		t.Errorf("bino.toml without engine version:\n--- got ---\n%q\n--- want ---\n%q", got, want)
	}
}


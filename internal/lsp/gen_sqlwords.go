//go:build ignore

// Command gen_sqlwords writes sqlwords_gen.go: the keyword and function names
// of the linked DuckDB, for query completion. Run via:
//
//	go generate ./internal/lsp/...
package main

import (
	"bytes"
	"database/sql"
	"fmt"
	"go/format"
	"os"

	_ "github.com/duckdb/duckdb-go/v2"
)

func main() {
	db, err := sql.Open("duckdb", "")
	must(err)
	defer db.Close()

	// Most unreserved keywords are DDL and session words; keep only the
	// window and ordering ones a SELECT uses.
	keywords := query(db, `SELECT DISTINCT upper(keyword_name) FROM duckdb_keywords()
		WHERE keyword_category IN ('reserved', 'type_function', 'column_name')
		   OR keyword_name IN ('over', 'partition', 'rows', 'range', 'preceding', 'following',
		                       'unbounded', 'current', 'nulls', 'first', 'last', 'recursive', 'filter')
		ORDER BY 1`)
	functions := query(db, `SELECT DISTINCT function_name FROM duckdb_functions()
		WHERE function_type IN ('scalar', 'aggregate', 'macro', 'table', 'table_macro')
		  AND regexp_full_match(function_name, '[a-z][a-z0-9_]*')
		ORDER BY 1`)

	var b bytes.Buffer
	b.WriteString("// Code generated by gen_sqlwords.go; DO NOT EDIT.\n\npackage lsp\n\n")
	writeList(&b, "duckdbKeywords", "DuckDB keywords a query uses", keywords)
	writeList(&b, "duckdbFunctions", "DuckDB scalar, aggregate, macro and table function names", functions)
	src, err := format.Source(b.Bytes())
	must(err)
	must(os.WriteFile("sqlwords_gen.go", src, 0o644))
}

func query(db *sql.DB, q string) []string {
	rows, err := db.Query(q)
	must(err)
	defer rows.Close()
	var out []string
	for rows.Next() {
		var s string
		must(rows.Scan(&s))
		out = append(out, s)
	}
	must(rows.Err())
	return out
}

func writeList(b *bytes.Buffer, name, doc string, words []string) {
	fmt.Fprintf(b, "// %s lists the %s.\nvar %s = []string{\n", name, doc, name)
	for _, w := range words {
		fmt.Fprintf(b, "\t%q,\n", w)
	}
	b.WriteString("}\n\n")
}

func must(err error) {
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
